// Embeds Kordoc's PDF text engine (hayro, Rust -> wasm) into src/io/hayroWasmData.ts.
//
// Kordoc 4.25.0 loads dist/hayro-pdf.wasm from disk or over the network. An Obsidian
// plugin ships main.js only, so HanMark carries the bytes inside the bundle: raw
// DEFLATE, then base64. The data file is committed and is rewritten only when it does
// not decode to the installed wasm, so the same commit embeds the same bytes on every
// machine regardless of the zlib build that runs this script.
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { deflateRawSync, inflateRawSync } from "node:zlib";

const source = new URL("../node_modules/kordoc/dist/hayro-pdf.wasm", import.meta.url);
const target = new URL("../src/io/hayroWasmData.ts", import.meta.url);
const kordoc = JSON.parse(
  await readFile(new URL("../node_modules/kordoc/package.json", import.meta.url), "utf8"),
);

const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");
const wasm = await readFile(source);
const digest = sha256(wasm);

async function embeddedDigest() {
  let text;
  try {
    text = await readFile(target, "utf8");
  } catch {
    return null;
  }
  const payload = /HAYRO_WASM_DEFLATE_BASE64 =\s*"([A-Za-z0-9+/=]+)"/u.exec(text)?.[1];
  if (!payload) return null;
  try {
    return sha256(inflateRawSync(Buffer.from(payload, "base64")));
  } catch {
    return null;
  }
}

if ((await embeddedDigest()) === digest) {
  console.log(`Embedded hayro-pdf.wasm is current (${wasm.byteLength} bytes, sha256 ${digest})`);
} else {
  const packed = deflateRawSync(wasm, { level: 9 });
  if (sha256(inflateRawSync(packed)) !== digest) {
    throw new Error("hayro-pdf.wasm did not survive the DEFLATE round trip.");
  }
  const lines = [
    "// GENERATED by scripts/gen-hayro-wasm.mjs. Do not edit.",
    `// hayro-pdf.wasm from kordoc ${kordoc.version} (see THIRD_PARTY_NOTICES.md): raw DEFLATE, base64.`,
    `export const HAYRO_WASM_SHA256 = "${digest}";`,
    `export const HAYRO_WASM_BYTE_LENGTH = ${wasm.byteLength};`,
    "export const HAYRO_WASM_DEFLATE_BASE64 =",
    `  "${packed.toString("base64")}";`,
    "",
  ];
  await writeFile(target, lines.join("\n"));
  console.log(
    `Embedded hayro-pdf.wasm (${wasm.byteLength} bytes, ${packed.byteLength} deflated, sha256 ${digest}) → src/io/hayroWasmData.ts`,
  );
}
