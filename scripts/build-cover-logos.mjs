// Builds src/io/coverLogoData.ts from the PNG files in assets/cover-logos (3.0.0).
// Each PNG is drawn from the SVG beside it at 640 px (about 550 dpi at 29.4 mm) with a transparent background:
//   node scripts/build-cover-logos.mjs --raster   (needs Playwright and a Chromium)
//   node scripts/build-cover-logos.mjs            (only rewrites the TypeScript module)
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const DIR = "assets/cover-logos";
const SIZE = 640;

if (process.argv.includes("--raster")) {
  const { chromium } = await import("playwright");
  const browser = await chromium.launch({ executablePath: process.env.HANMARK_BROWSER_EXECUTABLE || undefined, headless: true });
  const page = await browser.newPage({ viewport: { width: SIZE, height: SIZE }, deviceScaleFactor: 1 });
  for (const name of readdirSync(DIR).filter((file) => file.endsWith(".svg"))) {
    const svg = readFileSync(`${DIR}/${name}`, "utf8").replace(/width="100%" height="100%"/, `width="${SIZE}" height="${SIZE}"`);
    await page.setContent(`<html><body style="margin:0;background:transparent">${svg}</body></html>`);
    writeFileSync(`${DIR}/${name.replace(/\.svg$/, ".png")}`, await page.locator("svg").screenshot({ omitBackground: true }));
  }
  await browser.close();
}

function pngSize(bytes) {
  return { width: bytes.readUInt32BE(16), height: bytes.readUInt32BE(20) };
}

const entries = readdirSync(DIR)
  .filter((file) => file.endsWith(".png"))
  .sort()
  .map((file) => {
    const bytes = readFileSync(`${DIR}/${file}`);
    const { width, height } = pngSize(bytes);
    const key = file.replace(/\.png$/, "");
    return `  "${key}": {\n    width: ${width},\n    height: ${height},\n    png: "${bytes.toString("base64")}"\n  }`;
  });

writeFileSync(
  "src/io/coverLogoData.ts",
  `// Generated by scripts/build-cover-logos.mjs from assets/cover-logos. Do not edit.\n` +
    `export const COVER_LOGO_DATA: Readonly<Record<string, { width: number; height: number; png: string }>> = {\n${entries.join(",\n")}\n};\n`
);
console.log(`Cover logos: ${entries.length} written to src/io/coverLogoData.ts`);